# Prints the Homebrew formula for brewdust VERSION, installing the release
# archives listed in CHECKSUMS (the checksums.txt that build.sh writes).
#
#   scripts/release/formula.sh v0.1.0 dist/checksums.txt > brewdust.rb
#
# The archives are downloaded from the GitHub release for VERSION, or from
# URL_BASE when it's set (a file:// URL tests the formula against a local
# build).
set -eu

version=${1:?usage: formula.sh VERSION CHECKSUMS}
checksums=${2:?usage: formula.sh VERSION CHECKSUMS}
repo=${REPO:-BoxingOctopusCreative/brewdust}
base=${URL_BASE:-https://github.com/$repo/releases/download/$version}
number=${version#v}

# url and sha256 lines for one platform's archive, indented for the formula.
archive() {
	file="brewdust_${number}_$1_$2.tar.gz"
	sum=$(awk -v f="$file" '$2 == f { print $1 }' "$checksums")
	if [ -z "$sum" ]; then
		echo "$checksums has no checksum for $file" >&2
		exit 1
	fi
	printf '      url "%s/%s"\n      sha256 "%s"\n' "$base" "$file" "$sum"
}

# Each archive() runs in a command substitution, so check them up front: a
# failure there wouldn't stop the script.
for p in darwin_arm64 darwin_amd64 linux_arm64 linux_amd64; do
	archive "${p%_*}" "${p#*_}" >/dev/null
done

cat <<EOF
# Generated by scripts/release/formula.sh in https://github.com/$repo
# whenever a release is published. Don't edit it here.
class Brewdust < Formula
  desc "Find Homebrew packages gathering dust and clean them up"
  homepage "https://github.com/$repo"
  version "$number"
  license "MPL-2.0"

  on_macos do
    on_arm do
$(archive darwin arm64)
    end
    on_intel do
$(archive darwin amd64)
    end
  end

  on_linux do
    on_arm do
$(archive linux arm64)
    end
    on_intel do
$(archive linux amd64)
    end
  end

  def install
    bin.install "brewdust"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/brewdust --version")
  end
end
EOF
